describe('Lohnsteuer 2026 matches the official BMF check table (PAP 2026)', () => {
  for (const [gross, ...official] of PRUEFTABELLE_2026) {
    // Bis 603 € im Monat ist es bei uns ein Minijob (Pauschalsteuer); die Prüftabelle rechnet ohne Minijob-Regeln.
    if (gross / 12 <= 603) continue;
    it(`${gross} € Jahresbrutto, Steuerklassen I–VI`, () => {
      ['1', '2', '3', '4', '5', '6'].forEach((stkl, i) => {
        const r = calculateBruttoNetto({
          taxYear: '2026', taxClass: stkl, children: stkl === '2' ? '1' : '0', age: 30, federalState: 'other',
          churchTax: 'no', healthInsuranceType: 'statutory', kvZusatzbeitrag: 2.9, grossSalary: gross, period: 'year',
        });
        const monthly = Number(r.secondary!.find((s) => s.id === 'lohnsteuer')!.value);
        expect(Math.abs(monthly * 12 - official[i]), `StKl ${stkl}`).toBeLessThanOrEqual(0.5);
      });
    });
  }
});
